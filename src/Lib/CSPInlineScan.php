<?php
/**
 * Resumable public-page discovery with authenticated, short-lived loopback probes.
 *
 * @package securefusion
 */

namespace SecureFusion\Lib;

if ( ! defined( 'ABSPATH' ) ) {

	exit;

}

/**
 * Scan published content in small batches without granting any CSP permission.
 */
class CSPInlineScan {

	const OPTION = 'securefusion_inline_scan';

	/**
	 * Most pages one scan requests; templates repeat, so a sample finds the site's code.
	 */
	const MAX_PAGES = 200;

	/**
	 * Newest entries sampled per post type, and most used terms per taxonomy.
	 */
	const PER_TYPE     = 30;
	const PER_TAXONOMY = 3;

	/**
	 * Read the latest site scan.
	 *
	 * @return array
	 */
	public static function state() {

		$value = get_option( self::OPTION, [] );

		return is_array( $value ) ? $value : [];

	}

	/**
	 * Policy headers the first scanned page answered with.
	 *
	 * @return string|null Both headers joined, or null when no scan has measured them.
	 */
	public static function sent_policy() {

		$sent = self::state()['sent'] ?? null;

		return is_array( $sent ) ? trim( implode( ' ', array_map( 'strval', $sent ) ) ) : null;

	}

	/**
	 * Begin a new scan or resume the current one.
	 *
	 * @param bool $restart Explicit rescan request.
	 * @return array
	 */
	public static function start( $restart = false ) {

		$state = self::state();

		if ( ! $restart && $state ) {

			return $state;

		}

		$urls = [ home_url( '/' ) ];

		foreach ( array_diff( get_post_types( [ 'public' => true ] ), [ 'attachment', 'elementor_library' ] ) as $type ) {

			$url = get_post_type_archive_link( $type );

			if ( $url && self::is_site_url( $url ) ) {

				$urls[] = $url;

			}

		}

		$state = [
			'status'     => 'running',
			'phase'      => 'posts',
			'types'      => array_values( array_diff( get_post_types( [ 'public' => true ] ), [ 'attachment', 'elementor_library' ] ) ),
			'taxonomies' => array_values( get_taxonomies( [ 'public' => true ] ) ),
			'started'    => time(),
			'queue'      => array_values( array_unique( $urls ) ),
			'discovered' => count( array_unique( $urls ) ),
			'processed'  => 0,
			'failed'     => 0,
			'cached'     => 0,
			'errors'     => [],
			'current'    => '',
			'updated'    => time(),
		];

		update_option( self::OPTION, $state, false );

		return $state;

	}

	/**
	 * Restrict probes to this configured site's origin and public paths.
	 *
	 * @param string $url Candidate URL generated by WordPress.
	 * @return bool
	 */
	public static function is_site_url( $url ) {

		$home  = wp_parse_url( home_url( '/' ) );
		$parts = wp_parse_url( $url );

		if ( ! is_array( $parts ) || ! is_array( $home ) || isset( $parts['user'] ) || isset( $parts['pass'] ) ) {

			return false;

		}

		foreach ( [ 'scheme', 'host', 'port' ] as $part ) {

			if ( ( $home[ $part ] ?? '' ) !== ( $parts[ $part ] ?? '' ) ) {

				return false;

			}

		}

		$path = $parts['path'] ?? '/';
		$base = trailingslashit( $home['path'] ?? '/' );

		return 0 === strpos( trailingslashit( $path ), $base )
			&& ! preg_match( '#(?:^|/)(?:wp-admin|wp-login\.php|wp-cron\.php|xmlrpc\.php)(?:/|$)#i', rawurldecode( $path ) );

	}

	/**
	 * Queue a bounded sample of one post type or taxonomy.
	 *
	 * @param array $state Current scan.
	 * @return array
	 */
	private static function discover( $state ) {

		$urls = [];

		if ( 'posts' === $state['phase'] ) {

			$type = array_shift( $state['types'] );

			if ( null === $type ) {

				$state['phase'] = 'terms';

				return $state;

			}

			$ids = get_posts(
				[
					'post_type'              => $type,
					'post_status'            => 'publish',
					'has_password'           => false,
					'posts_per_page'         => self::PER_TYPE,
					'orderby'                => 'date',
					'order'                  => 'DESC',
					'fields'                 => 'ids',
					'no_found_rows'          => true,
					'update_post_meta_cache' => false,
					'update_post_term_cache' => false,
					'suppress_filters'       => false,
				]
			);

			foreach ( $ids as $id ) {

				$urls[] = get_permalink( $id );

			}

		} elseif ( 'terms' === $state['phase'] ) {

			$taxonomy = array_shift( $state['taxonomies'] );

			if ( null === $taxonomy ) {

				$state['phase'] = 'done';

				return $state;

			}

			$terms = get_terms(
				[
					'taxonomy'   => $taxonomy,
					'hide_empty' => true,
					'number'     => self::PER_TAXONOMY,
					'orderby'    => 'count',
					'order'      => 'DESC',
				]
			);

			foreach ( is_array( $terms ) ? $terms : [] as $term ) {

				$url = get_term_link( $term );

				if ( ! is_wp_error( $url ) ) {

					$urls[] = $url;

				}

			}

		}

		$state['queue']       = array_values( array_unique( array_filter( $urls, [ __CLASS__, 'is_site_url' ] ) ) );
		$state['discovered'] += count( $state['queue'] );

		return $state;

	}

	/**
	 * Process a single page; called only after AJAX nonce and capability checks.
	 *
	 * @param bool $restart Explicit rescan request.
	 * @return array|false
	 */
	public static function step( $restart = false ) {

		return CSPInlineLock::run(
			'scan',
			static function () use ( $restart ) {

				if ( $restart ) {

					self::start( true );

				}

				return self::advance();

			}
		);

	}

	/**
	 * Advance the catalog and probe after acquiring the scan lease.
	 *
	 * @return array
	 */
	private static function advance() {

		$state = self::start();

		if ( 'running' !== $state['status'] ) {

			return $state;

		}

		// Each pass consumes one post type or taxonomy, so this ends with the lists.
		while ( ! $state['queue'] && 'done' !== $state['phase'] ) {

			$state = self::discover( $state );

		}

		if ( $state['queue'] ) {

			$url              = array_shift( $state['queue'] );
			$state['current'] = $url;
			$state            = self::probe( $url, $state );

			++$state['processed'];

		}

		if ( $state['processed'] >= self::MAX_PAGES ) {

			$state['queue'] = [];
			$state['phase'] = 'done';

		}

		if ( 'running' === $state['status'] && ! $state['queue'] && 'done' === $state['phase'] ) {

			$state['status'] = $state['failed'] ? 'partial' : 'complete';

			if ( 'complete' === $state['status'] ) {

				CSPInlineRules::prune( (int) ( $state['started'] ?? 0 ) );

			}

		}

		$state['updated'] = time();
		$state['errors']  = array_slice( $state['errors'], -20 );

		update_option( self::OPTION, $state, false );

		return $state;

	}

	/**
	 * Fetch one public page without administrator cookies or external redirects.
	 *
	 * @param string $url URL from the published content catalog.
	 * @param array  $state Scan progress.
	 * @return array
	 */
	private static function probe( $url, $state ) {

		if ( ! self::is_site_url( $url ) ) {

			++$state['failed'];

			return $state;

		}

		$token = bin2hex( random_bytes( 32 ) );
		$key   = hash( 'sha256', $token );
		$path  = wp_parse_url( $url, PHP_URL_PATH );

		set_transient( 'securefusion_inline_request_' . $key, $path, MINUTE_IN_SECONDS );

		// Only a server-generated URL on the configured home origin reaches this request.
		$response = wp_remote_get(
			add_query_arg( '_sf_inline_scan', $key, $url ),
			[
				'timeout'             => 5,
				'redirection'         => 0,
				'limit_response_size' => 2 * MB_IN_BYTES + 1,
				'cookies'             => [],
				'headers'             => [
					'X-SecureFusion-Scan' => $token,
					'Cache-Control'       => 'no-cache',
				],
			]
		);

		$result = get_transient( 'securefusion_inline_result_' . $key );

		delete_transient( 'securefusion_inline_request_' . $key );
		delete_transient( 'securefusion_inline_result_' . $key );

		if ( is_wp_error( $response ) || 200 !== wp_remote_retrieve_response_code( $response ) ) {

			++$state['failed'];

			$state['errors'][] = $url . ' — ' . ( is_wp_error( $response ) ? $response->get_error_message() : 'HTTP ' . wp_remote_retrieve_response_code( $response ) );

			return $state;

		}

		// What the first page really answered with, so the settings screen can compare it with
		// what the settings ask for.
		if ( ! isset( $state['sent'] ) ) {

			$state['sent'] = [];

			foreach ( [ 'content-security-policy', 'content-security-policy-report-only' ] as $name ) {

				$state['sent'][ $name ] = substr( implode( ', ', (array) wp_remote_retrieve_header( $response, $name ) ), 0, 4096 );

			}

		}

		$html = wp_remote_retrieve_body( $response );
		$type = wp_remote_retrieve_header( $response, 'content-type' );

		if ( strlen( $html ) > 2 * MB_IN_BYTES || false === stripos( $type, 'text/html' ) || false === stripos( $html, '<html' ) ) {

			++$state['failed'];

			$state['errors'][] = $url . ' — ' . __( 'Not a complete HTML page below 2 MB.', 'secuplug' );

			return $state;

		}

		if ( ! is_array( $result ) ) {

			// A cache answered before WordPress ran, so nothing tells installed code from page
			// content. Listing all of it as unknown would bury the real findings; hosts are still facts.
			$result = array_filter(
				CSPInline::inspect_html( $html, $path ),
				static function ( $row ) {

					return isset( CSPInlineRules::HOST_TYPES[ $row['type'] ] );

				}
			);

			++$state['cached'];

		}

		if ( ! CSPInlineRules::observe( $result ) ) {

			++$state['failed'];

			$state['errors'][] = $url . ' — ' . __( 'Inventory was busy. Rescan to retry this page.', 'secuplug' );

		}

		if ( count( CSPInlineRules::all() ) >= CSPInlineRules::LIMIT ) {

			$state['status']   = 'partial';
			$state['errors'][] = __( 'The inline inventory is full. Remove obsolete records and rescan; discovery has stopped.', 'secuplug' );

		}

		return $state;

	}

	/**
	 * Verify the unguessable probe token and bind it to this site's exact path.
	 *
	 * @return string Verified request key or empty.
	 */
	public static function request_key() {

		$token = isset( $_SERVER['HTTP_X_SECUREFUSION_SCAN'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_X_SECUREFUSION_SCAN'] ) ) : '';
		$uri   = isset( $_SERVER['REQUEST_URI'] ) ? sanitize_url( wp_unslash( $_SERVER['REQUEST_URI'] ) ) : '';

		if ( ! preg_match( '/^[a-f0-9]{64}$/D', $token ) ) {

			return '';

		}

		$key      = hash( 'sha256', $token );
		$expected = get_transient( 'securefusion_inline_request_' . $key );
		$path     = wp_parse_url( $uri, PHP_URL_PATH );

		return is_string( $expected ) && is_string( $path ) && hash_equals( $expected, $path ) ? $key : '';

	}

}
